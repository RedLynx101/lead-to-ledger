// Builds the n8n workflow from source, so the rules that run in n8n are the same code
// the tests and scoring use: src/rules/rules.ts and src/leads/contact.ts have their
// types stripped and go into the Code node, with config/rules.json inlined.
//
//   node scripts/build-workflow.ts           write n8n/lead-intake.workflow.json
//   node scripts/build-workflow.ts --print   print the Code node's source and nothing else

import { readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
export const WORKFLOW_ID = 'ltlLeadIntake001';

function strip(file: string): string {
  const source = readFileSync(path.join(ROOT, file), 'utf8');
  return stripTypeScriptTypes(source, { mode: 'transform' })
    .replace(/^\s*export\s+/gm, '')
    .replace(/\n\s*\n\s*\n+/g, '\n\n')
    .trim();
}

export function codeNodeSource(): string {
  const config = readFileSync(path.join(ROOT, 'config/rules.json'), 'utf8').trim();
  return `// Generated by scripts/build-workflow.ts. Edit src/rules/rules.ts, not this node.
${strip('src/rules/rules.ts')}

${strip('src/leads/contact.ts')}

const CONFIG = ${config};

const body = $json.body ?? $json;
const form = body.form;
const synthetic = body.synthetic === true;
const rule = sortLead(form, CONFIG);

return {
  json: {
    submission_key: body.submission_key,
    synthetic,
    form,
    rule,
    skip_crm: Boolean(rule && rule.skip_crm),
    contact_input: { idProperty: 'email', id: form.email, properties: contactProperties(form, synthetic) },
  },
};`;
}

const SORT_NODE = 'Sort with rules';

const internalHeaders = {
  parameters: [{ name: 'x-ltl-internal', value: '={{ $env.LTL_INTERNAL_TOKEN }}' }],
};

export function buildWorkflow() {
  const nodes = [
    {
      id: 'a1000000-0000-4000-8000-000000000001',
      name: 'Form submitted',
      type: 'n8n-nodes-base.webhook',
      typeVersion: 2,
      position: [0, 200],
      webhookId: 'a1000000-0000-4000-8000-0000000000aa',
      parameters: { httpMethod: 'POST', path: 'lead-intake', responseMode: 'onReceived', options: {} },
    },
    {
      id: 'a1000000-0000-4000-8000-000000000002',
      name: SORT_NODE,
      type: 'n8n-nodes-base.code',
      typeVersion: 2,
      position: [240, 200],
      parameters: { mode: 'runOnceForEachItem', language: 'javaScript', jsCode: codeNodeSource() },
    },
    {
      id: 'a1000000-0000-4000-8000-000000000003',
      name: 'Skip the CRM?',
      type: 'n8n-nodes-base.if',
      typeVersion: 2.2,
      position: [480, 200],
      parameters: {
        options: {},
        conditions: {
          options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 2 },
          combinator: 'and',
          conditions: [
            {
              id: 'c1000000-0000-4000-8000-000000000001',
              leftValue: '={{ $json.skip_crm }}',
              rightValue: '',
              operator: { type: 'boolean', operation: 'true', singleValue: true },
            },
          ],
        },
      },
    },
    {
      id: 'a1000000-0000-4000-8000-000000000004',
      name: 'Upsert contact in HubSpot',
      type: 'n8n-nodes-base.httpRequest',
      typeVersion: 4.2,
      position: [720, 320],
      retryOnFail: true,
      maxTries: 3,
      waitBetweenTries: 2000,
      onError: 'continueErrorOutput',
      parameters: {
        method: 'POST',
        url: '={{ $env.HUBSPOT_BASE_URL }}/crm/objects/{{ $env.HUBSPOT_API_VERSION }}/contacts/batch/upsert',
        sendHeaders: true,
        headerParameters: { parameters: [{ name: 'Authorization', value: '=Bearer {{ $env.HUBSPOT_TOKEN }}' }] },
        sendBody: true,
        specifyBody: 'json',
        jsonBody: "={{ JSON.stringify({ inputs: [$('" + SORT_NODE + "').item.json.contact_input] }) }}",
        options: { timeout: 20000 },
      },
    },
    {
      id: 'a1000000-0000-4000-8000-000000000005',
      name: 'Triage: rules result or model',
      type: 'n8n-nodes-base.httpRequest',
      typeVersion: 4.2,
      position: [960, 200],
      onError: 'continueErrorOutput',
      parameters: {
        method: 'POST',
        url: '={{ $env.LTL_APP_URL }}/api/triage',
        sendHeaders: true,
        headerParameters: internalHeaders,
        sendBody: true,
        specifyBody: 'json',
        jsonBody:
          "={{ JSON.stringify({ submission_key: $('" + SORT_NODE + "').item.json.submission_key, form: $('" + SORT_NODE + "').item.json.form, rule: $('" + SORT_NODE + "').item.json.rule }) }}",
        // Calls wait their turn for the model, so a burst of leads needs a long timeout.
        options: { timeout: 600000 },
      },
    },
    {
      id: 'a1000000-0000-4000-8000-000000000006',
      name: 'Alert: contact upsert failed',
      type: 'n8n-nodes-base.httpRequest',
      typeVersion: 4.2,
      position: [960, 440],
      parameters: {
        method: 'POST',
        url: '={{ $env.LTL_APP_URL }}/api/alert',
        sendHeaders: true,
        headerParameters: internalHeaders,
        sendBody: true,
        specifyBody: 'json',
        jsonBody:
          "={{ JSON.stringify({ kind: 'crm_upsert_failed', key: $('" + SORT_NODE + "').item.json.submission_key, detail: String($json.error?.message ?? 'contact upsert failed') }) }}",
        options: { timeout: 10000 },
      },
    },
    {
      id: 'a1000000-0000-4000-8000-000000000007',
      name: 'Alert: AI step down',
      type: 'n8n-nodes-base.httpRequest',
      typeVersion: 4.2,
      position: [1200, 320],
      parameters: {
        method: 'POST',
        url: '={{ $env.LTL_APP_URL }}/api/alert',
        sendHeaders: true,
        headerParameters: internalHeaders,
        sendBody: true,
        specifyBody: 'json',
        jsonBody:
          "={{ JSON.stringify({ kind: 'ai_step_down', key: $('" + SORT_NODE + "').item.json.submission_key, detail: String($json.error?.message ?? 'triage call failed') }) }}",
        options: { timeout: 10000 },
      },
    },
  ];

  const connections = {
    'Form submitted': { main: [[{ node: SORT_NODE, type: 'main', index: 0 }]] },
    [SORT_NODE]: { main: [[{ node: 'Skip the CRM?', type: 'main', index: 0 }]] },
    'Skip the CRM?': {
      main: [
        [{ node: 'Triage: rules result or model', type: 'main', index: 0 }],
        [{ node: 'Upsert contact in HubSpot', type: 'main', index: 0 }],
      ],
    },
    'Upsert contact in HubSpot': {
      main: [
        [{ node: 'Triage: rules result or model', type: 'main', index: 0 }],
        [{ node: 'Alert: contact upsert failed', type: 'main', index: 0 }],
      ],
    },
    'Triage: rules result or model': {
      main: [[], [{ node: 'Alert: AI step down', type: 'main', index: 0 }]],
    },
  };

  return {
    id: WORKFLOW_ID,
    name: 'Lead intake: rules, CRM, triage',
    active: false,
    nodes,
    connections,
    settings: { executionOrder: 'v1' },
    pinData: {},
    meta: { templateCredsSetupCompleted: true },
    tags: [],
  };
}

if (import.meta.filename === process.argv[1] || process.argv[1]?.endsWith('build-workflow.ts')) {
  if (process.argv.includes('--print')) {
    console.log(codeNodeSource());
  } else {
    const file = path.join(ROOT, 'n8n/lead-intake.workflow.json');
    writeFileSync(file, `${JSON.stringify(buildWorkflow(), null, 2)}\n`);
    console.log('wrote n8n/lead-intake.workflow.json');
  }
}
